import base64
import os
from dotenv import load_dotenv
from mistralai import Mistral

from utils import write_string_to_csv


class ImageAnalyzer:
    """A class to analyze a sequence of images for task descriptions using AI models."""

    def __init__(
        self, frames_directory: str, vision_model: str, lang_model: str, api_key: str
    ):
        """
        Initialize the ImageAnalyzer.

        Args:
            frames_directory (str): Path to the directory containing the image frames.
            vision_model (str): The model used for image analysis.
            lang_model (str): The language model for text generation.
            api_key (str): API key for accessing the Mistral client.
        """
        self.frames_directory = frames_directory
        self.vision_model = vision_model
        self.lang_model = lang_model
        self.client = Mistral(api_key=api_key)

    def encode_image(self, image_path: str) -> str:
        """Encode an image to a base64 string.

        Args:
            image_path (str): The path of the image to encode.

        Returns:
            str: Base64 encoded image string, or None if encoding fails.
        """
        try:
            with open(image_path, "rb") as image_file:
                return base64.b64encode(image_file.read()).decode("utf-8")

        except Exception as e:
            print(f"Error encoding image {image_path}: {e}")
            return None

    def collect_images(self):
        """Collect and encode all images in the frames directory.

        Returns:
            list: A list of dictionaries containing base64 encoded images.
        """
        image_messages = []
        for filename in os.listdir(self.frames_directory):
            if filename.endswith(".jpg"):
                image_path = os.path.join(self.frames_directory, filename)
                base64_image = self.encode_image(image_path)
                if base64_image:
                    image_messages.append(
                        {
                            "type": "image_url",
                            "image_url": f"data:image/jpeg;base64,{base64_image}",
                        }
                    )
        return image_messages

    def collect_first_image(self):
        """Collect and encode the first image in the frames directory.

        Returns:
            list: A list containing a dictionary of the base64 encoded first image, or None if no image exists.
        """
        jpg_files = sorted(
            [f for f in os.listdir(self.frames_directory) if f.endswith(".jpg")]
        )

        if jpg_files:
            image_path = os.path.join(self.frames_directory, jpg_files[0])
            base64_image = self.encode_image(image_path)
            if base64_image:
                return [
                    {
                        "type": "image_url",
                        "image_url": f"data:image/jpeg;base64,{base64_image}",
                    }
                ]
        return None

    def caption_first_frame(self):
        """Generate a caption for the first frame of the video.

        Returns:
            str: A description of the first frame generated by the vision model.
        """
        image_messages = self.collect_first_image()

        content = {
            "type": "text",
            "text": "Describe what you can see in this image in one sentence.",
        }

        messages = [{"role": "user", "content": [content] + image_messages}]

        chat_response = self.client.chat.complete(
            model=self.vision_model, messages=messages
        )
        return chat_response.choices[0].message.content

    def caption_difference(self, previous_difference, sequential_image_messages):
        """Generate a caption describing the difference between two sequential frames.

        Args:
            previous_difference (str): The description of what happened previously.
            sequential_image_messages (list): A list of dictionaries containing the two sequential images.

        Returns:
            str: A description of the task happening between the two frames.
        """
        content = {
            "type": "text",
            "text": f"This happened previously:\n{previous_difference}\nDescribe the task happening between these two frames in one sentence.",
        }

        messages = [
            {
                "role": "user",
                "content": [content] + sequential_image_messages,
            }
        ]

        chat_response = self.client.chat.complete(
            model=self.vision_model, messages=messages
        )
        return chat_response.choices[0].message.content

    def generate_final_summary(self, combined_captions):
        """Generate a summary of all captions in one sentence.

        Args:
            combined_captions (str): All the generated captions combined.

        Returns:
            str: A summary of the combined captions.
        """
        messages = [
            {
                "role": "user",
                "content": "Summarize this in one sentence:\n" + combined_captions,
            }
        ]

        chat_response = self.client.chat.complete(
            model=self.lang_model, messages=messages
        )
        return chat_response.choices[0].message.content

    def generate_robot_command(self, video_summary):
        """Generate a robot command based on the video summary.

        Args:
            video_summary (str): A summary of what the human did in the video.

        Returns:
            str: A command for a robot arm to replicate the task.
        """
        messages = [
            {
                "role": "user",
                "content": (
                    "This is what the human did:\n"
                    + video_summary
                    + "\n\n"
                    + "Rewrite this into a general command for a robot arm to replicate the task.\n\n"
                    + "Example: If the human description is <The person in the video placed the apple on the plate.>, "
                    + "output something like <Pick up the apple and place it on the plate.>"
                ),
            }
        ]

        chat_response = self.client.chat.complete(
            model=self.lang_model, messages=messages
        )
        return chat_response.choices[0].message.content


if __name__ == "__main__":
    load_dotenv()
    api_key = os.environ["MISTRAL_API_KEY"]

    frames_directory = "frames/plate"
    command_file = "frames/plate/robot_command.csv"

    vision_model = "pixtral-12b-2409"
    lang_model = "mistral-large-latest"

    caption_list = []

    analyzer = ImageAnalyzer(frames_directory, vision_model, lang_model, api_key)
    grounding = analyzer.caption_first_frame()
    caption_list.append("This is the start of the video: " + grounding)

    frame_list = analyzer.collect_images()

    for i in range(len(frame_list) - 1):
        if i == 0:
            difference = grounding

        consecutive_frames = frame_list[i : i + 2]

        if len(consecutive_frames) == 2:
            difference = analyzer.caption_difference(difference, consecutive_frames)
            caption_list.append(
                "This is happening between two consecutive frames: " + difference
            )

    combined_captions = "\n\n".join(caption_list)

    video_summary = analyzer.generate_final_summary(combined_captions)
    robot_command = analyzer.generate_robot_command(video_summary)

    write_string_to_csv(command_file, robot_command)
